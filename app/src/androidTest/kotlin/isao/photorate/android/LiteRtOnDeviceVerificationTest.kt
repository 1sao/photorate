  private val assets = InstrumentationRegistry.getInstrumentation().context.assets

  // Optional instrumentation args:
  //   gpuBackend: "OPENCL" / "OPENGL" / "WEBGPU" to force a GPU backend
  //   gpuPrecision: "FP16" / "FP32" / "DEFAULT" (default: FP32 — the GPU
  //     delegate's fp16 reductions drift by ~1e-2 and can flip a marginal
  //     NMS box; FP32 keeps the box set identical to CPU at nearly the same
  //     GPU latency, so it is the accuracy-safe default here).
  private val gpuBackend: CompiledModel.GpuOptions.Backend? =
    InstrumentationRegistry.getArguments().getString("gpuBackend")?.let {
      CompiledModel.GpuOptions.Backend.valueOf(it)
    }
  private val gpuPrecision: CompiledModel.GpuOptions.Precision? =
    InstrumentationRegistry.getArguments().getString("gpuPrecision")?.let {
      CompiledModel.GpuOptions.Precision.valueOf(it)
    } ?: CompiledModel.GpuOptions.Precision.FP32

