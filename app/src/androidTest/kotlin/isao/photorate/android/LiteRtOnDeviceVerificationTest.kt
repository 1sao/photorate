  /**
   * Pose task gate: decoded keypoints must match the reference (argmax bins over 512, split ratio
   * 2.0).
   */
  private fun poseTaskGate(
    runner: CompiledModelRunner,
    tag: String,
  ): TaskResult {
    val kps =
      LiteRtRtmModels.decodeSimcc(
        runner.readOutput(0),
        runner.readOutput(1),
      )
    val ref = readRefF32("pose_${tag}_kps.npy")
    var maxPx = 0f
    for (i in 0 until 21) {
      maxPx =
        max(
          maxPx,
          abs(kps[i * 3] - ref[i * 3]),
        )
      maxPx =
        max(
          maxPx,
          abs(kps[i * 3 + 1] - ref[i * 3 + 1]),
        )
    }
    log("pose_${tag}_kp_max_px_diff=$maxPx")
    return TaskResult(
      maxPx < 3f,
      "pose $tag keypoints ok ($maxPx px)",
    )
  }

  /**
   * Quantized variants of the two shipped models (accuracy-safe-quantization skill): fp16
   * float-casting and dynamic-range int8, generated by ml/litert/scripts/quantize_models.py and
   * packaged as app assets.
   *
   * fp16 (weights fp16, compute fp32, op set unchanged) is the candidate quality row — same strict
   * GPU residency + parity + task gates as the float32 baseline. int8 is measured the same way, but
   * per the skill its host-CPU numbers are pessimistic and the task gate is the verdict; an int8
   * miss is logged as a finding, not a shipping blocker (fp16 is the shrink that ships if int8
   * degrades).
   */
  @Test
  fun verifyQuantizedVariants() {
    verifyQuantizedVariant(
      asset = "rtmdet_hand_320_f16.tflite",
      prefix = "det",
      gates = detGates,
      taskGate = ::detectorTaskGate,
      requireGpuCompile = true,
      assertTaskGate = true,
    )
    verifyQuantizedVariant(
      asset = "rtmdet_hand_320_i8.tflite",
      prefix = "det",
      gates = detGates,
      taskGate = ::detectorTaskGate,
      requireGpuCompile = false,
      assertTaskGate = false,
    )
    verifyQuantizedVariant(
      asset = "rtmpose_hand_256_f16.tflite",
      prefix = "pose",
      gates = poseGates,
      taskGate = ::poseTaskGate,
      requireGpuCompile = true,
      assertTaskGate = true,
    )
    verifyQuantizedVariant(
      asset = "rtmpose_hand_256_i8.tflite",
      prefix = "pose",
      gates = poseGates,
      taskGate = ::poseTaskGate,
      requireGpuCompile = false,
      assertTaskGate = false,
    )
  }

  private fun verifyQuantizedVariant(
    asset: String,
    prefix: String,
    gates: List<Gate>,
    taskGate: (CompiledModelRunner, String) -> TaskResult,
    requireGpuCompile: Boolean,
    assertTaskGate: Boolean,
  ) {
    log("quantized_variant_asset=$asset")
    verifyModel(
      asset = asset,
      tags = listOf("rand", "real"),
      inputRef = { tag -> "${prefix}_${tag}_input.npy" },
      gates = gates,
      taskGate = taskGate,
      // int8 corr is log-only — the
      // task gate is the verdict
      // (host CPU
      // int kernels are
      // pessimistically worse than
      // the device GPU).
      corrMin = if (assertTaskGate) 0.95f else 0f,
      requireGpuCompile = requireGpuCompile,
      assertTaskGate = assertTaskGate,
    )
  }

  /**
   * Micro-probe of the GPU delegate's supported op set (on-device-verification skill): every op
   * used by the two RTM models, as a ~1KB single-op model, compiled+run under several accelerator
   * configs. Logs SUPPORTED / NOT_SUPPORTED per op per config. Probes are generated by
   * ml/litert/scripts/probe_ops.py.
   *
   * NOTE: the app manifest declares <uses-native-library> for libvndksupport.so and libOpenCL.so —
   * without those, the ClGl accelerator cannot dlopen the vendor OpenCL runtime, silently falls
   * back to GL, and fails at buffer creation. The probe results below were collected with the fix
   * in place.
   */
  @Test
  fun gpuOpSupportProbe() {
    val probes =
      listOf(
        "CONV_2D",
        "DEPTHWISE_CONV_2D",
        "FULLY_CONNECTED",
        "ADD",
        "MUL",
        "SUB",
        "DIV",
        "MAXIMUM",
        "MINIMUM",
        "LOGISTIC",
        "RELU",
        "RELU6",
        "RELU_0_TO_1",
        "CONCATENATION",
        "RESHAPE",
        "TRANSPOSE",
        "PAD",
        "MEAN",
        "SUM",
        "SQRT",
        "GATHER",
        "SPLIT_V",
        "BATCH_MATMUL",
        "SOFTMAX",
        "MAX_POOL_2D",
        "AVERAGE_POOL_2D",
        "RESIZE_NEAREST_NEIGHBOR",
        "RESIZE_BILINEAR",
        "STRIDED_SLICE",
        "SLICE",
        "SQUEEZE",
        // MobileCLIP-S1 combined tflite ops (added for the CLIP GPU check).
        "GELU",
        "RSQRT",
        "SQUARED_DIFFERENCE",
        // Rest
        // of
        // the
        // S1 op
        // inventory (completeness sweep): ABS (f32),
        // CAST
        // (int64->int32 token ids) and EMBEDDING_LOOKUP (int32 ids).
        "ABS",
        "CAST",
        "EMBEDDING_LOOKUP",
      )
    val gpuOpenCl =
      CompiledModel.Options(Accelerator.GPU).apply {
        gpuOptions = CompiledModel.GpuOptions(backend = CompiledModel.GpuOptions.Backend.OPENCL)
      }
    val gpuTex2d =
      CompiledModel.Options(Accelerator.GPU).apply {
        gpuOptions =
          CompiledModel.GpuOptions(
            bufferStorageType = CompiledModel.GpuOptions.BufferStorageType.TEXTURE_2D
          )
      }
    val gpuExternal =
      CompiledModel.Options(Accelerator.GPU).apply {
        gpuOptions =
          CompiledModel.GpuOptions(
            externalTensorsMode = true,
            externalTensorPattern = "*",
          )
      }
    val configs =
      listOf(
        "GPU" to CompiledModel.Options(Accelerator.GPU),
        "CPU_GPU" to
          CompiledModel.Options(
            Accelerator.CPU,
            Accelerator.GPU,
          ),
        "GPU_OPENCL" to gpuOpenCl,
        "GPU_TEX2D" to gpuTex2d,
        "GPU_EXT" to gpuExternal,
      )
    // Probes are packaged with the TEST apk (androidTest
    // assets), so read
    // them from the instrumentation context, not the app
    // context.
    val testContext = InstrumentationRegistry.getInstrumentation().context
    withEgl {
      for ((tag, options) in configs) {
        for (name in probes) {
          val result =
            try {
              CompiledModel.create(
                  testContext.assets,
                  "$name.tflite",
                  options,
                  null,
                )
                .use { model ->
                  // The accelerator(s) declare which buffer types the IO
                  // tensors accept — log them so the buffer strategy is
                  // evidence-driven, not guessed.
                  val req =
                    try {
                      model.getInputBufferRequirements("x").supportedTypes.joinToString(",") {
                        it.name
                      }
                    } catch (e: LiteRtException) {
                      "ERR:${e.message?.take(120)}"
                    }
                  log("probe_${name}_${tag}_req=$req")
                  val ins = model.createInputBuffers()
                  val outs = model.createOutputBuffers()
                  try {
                    // Dtypes must stay in sync with probe_ops.py:
                    // CAST is int64->int32, EMBEDDING_LOOKUP takes
                    // int32 ids (f32 output); every other probe is f32.
                    when (name) {
                      "CAST" -> ins[0].writeLong(LongArray(ins[0].readLong().size))
                      "EMBEDDING_LOOKUP" -> ins[0].writeInt(IntArray(ins[0].readInt().size))
                      else -> ins[0].writeFloat(FloatArray(ins[0].readFloat().size))
                    }
                    model.run(
                      ins,
                      outs,
                    )
                    // CAST outputs int32; every other probe outputs f32.
                    if (name == "CAST") outs[0].readInt() else outs[0].readFloat()
                    "SUPPORTED"
                  } finally {
                    ins.forEach { it.close() }
                    outs.forEach { it.close() }
                  }
                }
            } catch (e: LiteRtException) {
              "NOT_SUPPORTED: ${e.message?.take(400)}"
            }
          log("probe_${name}_$tag=$result")
        }
      }
    }
  }

  /**
   * The same treatment attempted on the *original* in-graph-NMS detector (`end2end.onnx` ->
   * `rtmdet_hand_320_end2end_f32.tflite`), to document why the head-cut `_f32clean` variant is the
   * GPU-clean one: NMS/TOPK and data-dependent Gathers have no GPU kernels, and onnx2tf caps the
   * dynamic NMS output at 5 detections while the source ONNX keeps 39/53 on the two ref inputs. Not
   * a gate — this model is not shipped; the log rows are the finding. The pose `end2end.onnx` is
   * not covered: its dynamic batch dims make onnx2tf fail outright (shape inference error on
   * `Mul_235`).
   */
  @Test
  fun originalDetectorGpuAttempt() {
    val asset = "rtmdet_hand_320_end2end_f32.tflite"
    withEgl {
      // 1) Strict GPU compile —
      // expected to fail on
      // NON_MAX_SUPPRESSION_V4 /
      //    TOPK_V2 / data-dependent
      // GATHER / RELU_0_TO_1.
      try {
        CompiledModelRunner.fromAssets(
            context,
            asset,
            CompiledModel.Options(Accelerator.GPU),
          )
          .use { log("original_det_gpu=COMPILED (unexpected)") }
      } catch (e: LiteRtException) {
        log("original_det_gpu=COMPILE_FAILED: ${e.message?.take(120)}")
      }
      // 2) CPU run: the 5 capped
      // detections must match the
      // ONNX top-5, and
      //    report the CPU latency
      // baseline.
      CompiledModelRunner.fromAssets(
          context,
          asset,
          CompiledModel.Options(Accelerator.CPU),
        )
        .use { runner ->
          runTimed(
            runner,
            "det_real_input.npy",
          ) // warmup
          runner.writeInput(
            0,
            readRefF32("det_real_input.npy"),
          )
          runner.run()
          val dets = runner.readOutput(0)
          val ref = readRefF32("det_real_end2end_dets.npy")
          val refRows = ref.size / 5
          val rows = dets.size / 5
          var maxDiff = 0f
          for (i in
            0 until
              min(
                dets.size,
                ref.size,
              )) {
            maxDiff =
              max(
                maxDiff,
                abs(dets[i] - ref[i]),
              )
          }
          log("original_det_cpu out_rows=$rows ref_rows=$refRows max_diff_vs_onnx_top5=$maxDiff")
          val timing =
            (0 until 10)
              .map {
                runTimed(
                  runner,
                  "det_real_input.npy",
                )
              }
              .sorted()
          log("original_det_cpu latency_median_ms=${timing[timing.size / 2]}")
        }
    }
  }

