/**
 * On-device verification of the LiteRT-converted RTM hand models (see the ml/litert/ model recipe
 * and the on-device-verification skill).
 *
 * For each model, on each accelerator (CPU control, then strict GPU):
 * - GPU residency: a strict `Accelerator.GPU` compile succeeds (no CPU fallback is possible in
 *   CompiledModel — failure names the op).
 * - Numeric parity vs the host-dumped ONNX references (correlation + max abs diff on every output).
 * - Task gate: detector NMS box set must match the reference set (count + max box diff); pose
 *   decoded keypoints must stay within a few px of the reference.
 * - Latency: warmup once (shader compile), then 10 timed run+readback inferences, reporting
 *   median/mean.
 *
 * References are in ml/litert/refs (generated by dump_refs.py from the f32clean ONNX models) and
 * are packaged as test assets. Every result row is logged with the `LITERT` tag for
 * machine-parseable collection.
 *
 * GPU buffers: the GL accelerator's managed IO buffers default to GL textures, whose allocation
 * requires a *current* EGL context (litert's GlTexture wraps the TFLite GL delegate's GlTexture,
 * which calls glGenTextures on whatever context is current). Instrumentation tests have no GL
 * context by default, so every GPU path in this file runs inside an [EglEnv] scope.
 */
@RunWith(AndroidJUnit4::class)
class LiteRtOnDeviceVerificationTest {

