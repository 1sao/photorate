  /**
   * Runs one model on CPU then strict GPU: loads the fixed inputs, checks numeric parity on every
   * output, runs the model-specific task gate, and benchmarks run+readback after a warmup.
   *
   * Quantized-variant knobs (see [verifyQuantizedVariant]): [corrMin] lowers the correlation floor
   * (int8 corr is log-only), [requireGpuCompile] downgrades a strict-GPU compile failure to a
   * logged finding, and [assertTaskGate] downgrades a task-gate miss to a logged finding.
   */
  private fun verifyModel(
    asset: String,
    tags: List<String>,
    inputRef: (String) -> String,
    gates: List<Gate>,
    taskGate: (CompiledModelRunner, String) -> TaskResult,
    corrMin: Float = 0.99f,
    requireGpuCompile: Boolean = true,
    assertTaskGate: Boolean = true,
  ) {
    val available: Set<Accelerator> =
      try {
        Environment.create().let { env ->
          try {
            env.getAvailableAccelerators()
          } finally {
            env.close()
          }
        }
      } catch (e: LiteRtException) {
        emptySet()
      }
    log("available_accelerators=$available")
    val gpuSupported = available.contains(Accelerator.GPU)
    log("gpu_supported=$gpuSupported")
    assertTrue(
      "device reports no GPU accelerator",
      gpuSupported,
    )

    // GPU (GL) IO buffers need a current EGL context —
    // hold one for the
    // whole CPU+GPU loop (harmless for the CPU pass).
    withEgl {
      for (accel in
        listOf(
          Accelerator.CPU,
          Accelerator.GPU,
        )) {
        val runner =
          try {
            val options = CompiledModel.Options(accel)
            if (accel == Accelerator.GPU) {
              options.gpuOptions =
                CompiledModel.GpuOptions(
                  backend = gpuBackend ?: CompiledModel.GpuOptions.Backend.OPENCL,
                  precision = gpuPrecision,
                )
            }
            CompiledModelRunner.fromAssets(
              context,
              asset,
              options,
            )
          } catch (e: LiteRtException) {
            log("compile_failed accel=$accel err=${e.message?.take(300)}")
            if (accel == Accelerator.GPU && !requireGpuCompile) {
              log("$asset gpu=COMPILE_FAILED (documented, not a gate)")
              continue
            }
            assertTrue(
              "strict $accel compile failed for $asset: ${e.message}",
              accel != Accelerator.GPU,
            )
            continue
          }
        runner.use {
          // Warmup: first GPU inference includes shader compilation.
          runTimed(
            runner,
            inputRef(tags.first()),
          )
          // Numeric parity on every output, every tag. Each gate's ref is
          // matched to the corresponding model output by index.
          val outputs = tags.associateWith { tag ->
            runModel(
              runner,
              inputRef(tag),
            )
          }
          for (tag in tags) {
            val actualAll = outputs.getValue(tag)
            gates.forEachIndexed { i, gate ->
              val ref = readRefF32(gate.ref(tag))
              val corr =
                correlation(
                  actualAll[i],
                  ref,
                )
              val diff =
                maxAbsDiff(
                  actualAll[i],
                  ref,
                )
              log("${gate.name}_${tag}_accel=$accel corr=$corr max_abs_diff=$diff")
              assertTrue(
                "${gate.name} $tag on $accel lost correlation: $corr",
                corr > corrMin,
              )
            }
          }
          // Task gate on the real input (a real image is the honest check).
          val gateResult =
            taskGate(
              runner,
              "real",
            )
          if (assertTaskGate) {
            assertTrue(
              "task gate failed on $accel: ${gateResult.msg}",
              gateResult.ok,
            )
          } else {
            log("task_gate accel=$accel verdict=${gateResult.msg} (documented, not a gate)")
          }
          // Latency: run + readback, after warmup.
          val timings =
            (0 until LATENCY_RUNS).map {
              runTimed(
                runner,
                inputRef(tags.first()),
              )
            }
          val median = timings.sorted()[timings.size / 2]
          val mean = timings.average()
          log(
            "latency asset=$asset accel=$accel runs=${
              timings.joinToString(
                ","
              )
            } median_ms=$median mean_ms=${"%.1f".format(mean)}"
          )
        }
      }
    }
  }

  private fun runModel(
    runner: CompiledModelRunner,
    inputRef: String,
  ): List<FloatArray> {
    runner.writeInput(0, readRefF32(inputRef))
    runner.run()
    return (0 until runner.outputBuffers.size).map { runner.readOutput(it) }
  }

  private fun runTimed(runner: CompiledModelRunner, inputRef: String): Long {
    runner.writeInput(0, readRefF32(inputRef))
    val start = System.nanoTime()
    runner.run()
    runner.readOutput(0) // readback is the sync point — benchmark
    // run+readback together
    return (System.nanoTime() - start) / 1_000_000
  }

  /** Runs [block] with a current EGL context (required by the GL accelerator's IO buffers). */
  private fun <T> withEgl(block: () -> T): T {
    val egl = EglEnv()
    try {
      return block()
    } finally {
      egl.release()
    }
  }

  /**
   * Minimal offscreen EGL environment: display + ES2 context + 1x1 pbuffer surface made current.
   * Enough for glGenTextures / glTexSubImage2D used by litert's GL tensor buffers.
   */
  private class EglEnv {
    private val display: EGLDisplay
    private val context: EGLContext
    private val surface: EGLSurface

    init {
      display = EGL14.eglGetDisplay(EGL14.EGL_DEFAULT_DISPLAY)
      check(display != EGL14.EGL_NO_DISPLAY) { "eglGetDisplay failed" }
      val major = IntArray(1)
      val minor = IntArray(1)
      check(
        EGL14.eglInitialize(
          display,
          major,
          0,
          minor,
          0,
        )
      ) {
        "eglInitialize failed"
      }
      val configs = arrayOfNulls<EGLConfig>(1)
      val numConfigs = IntArray(1)
      // GL shader storage buffers
      // (litert's GlBuffer IO) need
      // ES 3.1+.
      // EGL14 lacks
      // EGL_OPENGL_ES3_BIT; its
      // value is 0x0040
      // (EGL_KHR_create_context).
      val configAttrs =
        intArrayOf(
          EGL14.EGL_SURFACE_TYPE,
          EGL14.EGL_PBUFFER_BIT,
          EGL14.EGL_RENDERABLE_TYPE,
          0x0040, // EGL_OPENGL_ES3_BIT
          EGL14.EGL_NONE,
        )
      check(
        EGL14.eglChooseConfig(
          display,
          configAttrs,
          0,
          configs,
          0,
          configs.size,
          numConfigs,
          0,
        ) && numConfigs[0] > 0
      ) {
        "eglChooseConfig failed"
      }
      val contextAttrs =
        intArrayOf(
          EGL14.EGL_CONTEXT_CLIENT_VERSION,
          3,
          EGL14.EGL_NONE,
        )
      context =
        EGL14.eglCreateContext(
          display,
          configs[0],
          EGL14.EGL_NO_CONTEXT,
          contextAttrs,
          0,
        )
      check(context != EGL14.EGL_NO_CONTEXT) { "eglCreateContext failed" }
      val surfaceAttrs =
        intArrayOf(
          EGL14.EGL_WIDTH,
          1,
          EGL14.EGL_HEIGHT,
          1,
          EGL14.EGL_NONE,
        )
      surface =
        EGL14.eglCreatePbufferSurface(
          display,
          configs[0],
          surfaceAttrs,
          0,
        )
      check(surface != EGL14.EGL_NO_SURFACE) { "eglCreatePbufferSurface failed" }
      check(
        EGL14.eglMakeCurrent(
          display,
          surface,
          surface,
          context,
        )
      ) {
        "eglMakeCurrent failed"
      }
    }

    fun release() {
      EGL14.eglMakeCurrent(
        display,
        EGL14.EGL_NO_SURFACE,
        EGL14.EGL_NO_SURFACE,
        EGL14.EGL_NO_CONTEXT,
      )
      EGL14.eglDestroySurface(
        display,
        surface,
      )
      EGL14.eglDestroyContext(
        display,
        context,
      )
      EGL14.eglTerminate(display)
    }
  }

  // --- reference npy loading ----------------------------------------------

  private fun readRefF32(name: String): FloatArray {
    // The refs dir is added to the androidTest assets by
    // CONTENT (flat), so
    // the npy files sit at the assets root, not under
    // ml/litert/refs/.
    assets.open(name).use { input: InputStream ->
      val bytes = input.readBytes()
      val (_, dataOffset) = parseNpyHeader(bytes)
      val count = (bytes.size - dataOffset) / 4
      val buffer =
        ByteBuffer.wrap(
            bytes,
            dataOffset,
            count * 4,
          )
          .order(ByteOrder.LITTLE_ENDIAN)
      val out = FloatArray(count)
      buffer.asFloatBuffer().get(out)
      return out
    }
  }

  /** Parses a numpy v1.0 .npy header; returns (shape, dataOffset). */
  private fun parseNpyHeader(bytes: ByteArray): Pair<IntArray, Int> {
    require(bytes.size > 10 && bytes[0] == 0x93.toByte() && bytes[1] == 'N'.code.toByte()) {
      "not a numpy file"
    }
    val headerLen = (bytes[8].toInt() and 0xFF) or ((bytes[9].toInt() and 0xFF) shl 8)
    val header =
      String(
        bytes,
        10,
        headerLen,
        Charsets.US_ASCII,
      )
    val shapeMatch =
      Regex("'shape':\\s*\\(([^)]*)\\)").find(header)
        ?: Regex("\"shape\":\\s*\\(([^)]*)\\)").find(header)
    require(shapeMatch != null) { "shape not found in header: $header" }
    val dims =
      shapeMatch.groupValues[1]
        .split(",")
        .map { it.trim() }
        .filter { it.isNotEmpty() && it != "1" && it != "0" }
        .map { it.toInt() }
    return dims.toIntArray() to (10 + headerLen)
  }

  // --- stats ---------------------------------------------------------------

  private fun correlation(a: FloatArray, b: FloatArray): Float {
    var meanA = 0f
    var meanB = 0f
    for (i in a.indices) {
      meanA += a[i]
      meanB += b[i]
    }
    meanA /= a.size
    meanB /= a.size
    var cov = 0.0
    var varA = 0.0
    var varB = 0.0
    for (i in a.indices) {
      val da = a[i] - meanA
      val db = b[i] - meanB
      cov += da * db
      varA += da * da
      varB += db * db
    }
    if (varA == 0.0 && varB == 0.0) return 1f
    return (cov / (kotlin.math.sqrt(varA) * kotlin.math.sqrt(varB))).toFloat()
  }

  private fun maxAbsDiff(a: FloatArray, b: FloatArray): Float {
    var worst = 0f
    for (i in a.indices) {
      worst =
        max(
          worst,
          abs(a[i] - b[i]),
        )
    }
    return worst
  }

