  /**
   * Detector task gate: the NMS-kept box set must match the reference set order-independently (a
   * ~1e-5 score tie can flip anchor order between runtimes, so pairwise index comparison is too
   * brittle). Every reference box must have a device box with IoU > 0.5.
   */
  private fun detectorTaskGate(
    runner: CompiledModelRunner,
    tag: String,
  ): TaskResult {
    val boxes = runner.readOutput(0)
    val scores = runner.readOutput(1)
    val keep = LiteRtRtmModels.nmsAnchors(boxes, scores)
    val ref = readRefF32("det_${tag}_refboxes.npy")
    val refCount = ref.size / 5
    var matched = 0
    var minMatchIou = 1f
    val used = BooleanArray(keep.size)
    for (r in 0 until refCount) {
      val rx1 = ref[r * 5]
      val ry1 = ref[r * 5 + 1]
      val rx2 = ref[r * 5 + 2]
      val ry2 = ref[r * 5 + 3]
      var bestIou = 0f
      var bestIdx = -1
      for (k in keep.indices) {
        if (used[k]) continue
        val o = keep[k] * 4
        val iou =
          MathOps.iou(
            rx1,
            ry1,
            rx2,
            ry2,
            boxes[o],
            boxes[o + 1],
            boxes[o + 2],
            boxes[o + 3],
          )
        if (iou > bestIou) {
          bestIou = iou
          bestIdx = k
        }
      }
      if (bestIou > 0.5f) {
        used[bestIdx] = true
        matched++
        minMatchIou =
          min(
            minMatchIou,
            bestIou,
          )
      }
    }
    log(
      "det_${tag}_nms_keep=${keep.size} ref_keep=$refCount matched=$matched min_match_iou=$minMatchIou"
    )
    return TaskResult(
      matched == refCount,
      "det $tag $matched/$refCount boxes matched",
    )
  }

